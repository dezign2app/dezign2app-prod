import { describe, it, expect } from "vitest";
import { generateSectionLayout } from "../webClients/nextjs/v16/layoutGenerators";
import { BackendNode } from "@/types/canvas";

describe("Autogenerated Layout Sidebar Component", () => {
  it("compiles protected layout with static sidebar component binding", () => {
    const layoutNode: BackendNode = {
      id: "layout-node-1",
      type: "webPage",
      data: {
        label: "layout",
        isLayout: true,
        sections: [
          {
            id: "sec-nav",
            name: "App Sidebar Navigation",
            renderMode: "server",
            loadStrategy: "eager",
            actions: [],
            componentBindings: [
              {
                id: "comp-sidebar-test",
                name: "AppSidebar",
                label: "AppSidebar",
                componentType: "sidebar",
                variant: "default",
                propMappings: {
                  sidebarTitle: "Private Section",
                  sidebarNavMode: "static",
                  sidebarCollapsible: "icon",
                  sidebarVariant: "sidebar",
                  sidebarStaticItems: [
                    { id: "nav-1", name: "Dashboard", link: "/dashboard" },
                    { id: "nav-2", name: "Settings", link: "/settings" },
                  ],
                },
              },
            ],
          },
          {
            id: "sec-children",
            name: "Page Content ({children})",
            renderMode: "server",
            loadStrategy: "eager",
            actions: [],
            componentBindings: [],
          },
        ],
      },
    };

    const code = generateSectionLayout("private", true, "Protected app layout", undefined, layoutNode);

    // Verify imports
    expect(code).toContain('import {');
    expect(code).toContain('SidebarProvider');
    expect(code).toContain('Sidebar');
    expect(code).toContain('@workspace/ui/components/sidebar');
    expect(code).toContain('import Link from "next/link";');

    // Verify layout JSX
    expect(code).toContain('<SidebarProvider className="min-h-screen">');
    expect(code).toContain('<Sidebar collapsible="icon" variant="sidebar">');
    expect(code).toContain('Private Section');
    expect(code).toContain('Dashboard');
    expect(code).toContain('href="/dashboard"');
    expect(code).toContain('Settings');
    expect(code).toContain('href="/settings"');
    expect(code).toContain('<SidebarTrigger');
    expect(code).toContain('{children}');
  });

  it("compiles layout without sidebar as standard header layout", () => {
    const layoutNode: BackendNode = {
      id: "layout-node-plain",
      type: "webPage",
      data: {
        label: "layout",
        isLayout: true,
        sections: [
          {
            id: "sec-nav",
            name: "Header Navigation",
            renderMode: "server",
            loadStrategy: "eager",
            actions: [],
            componentBindings: [],
          },
          {
            id: "sec-children",
            name: "Page Content ({children})",
            renderMode: "server",
            loadStrategy: "eager",
            actions: [],
            componentBindings: [],
          },
        ],
      },
    };

    const code = generateSectionLayout("public", false, "Public layout", undefined, layoutNode);

    expect(code).not.toContain("SidebarProvider");
    expect(code).toContain('<div className="min-h-screen flex flex-col bg-background text-foreground">');
    expect(code).toContain('{children}');
  });
});

